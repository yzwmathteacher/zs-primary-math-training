function calcStandardAnswer(question) {
    try {
        let str = question
            .replaceAll("×", "*")
            .replaceAll("÷", "/")
            .replace(/(\d+)\/(\d+)/g, "($1/$2)");
        let res = eval(str);
        return Number(res.toFixed(4));
    } catch (e) {
        return null;
    }
}

